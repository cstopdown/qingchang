import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('真实 VocalVerse 干声评分并在刷新后保留', async ({ page }) => {
  const fixturePath = process.env.QINGCHANG_REAL_AI_FIXTURE
  test.skip(process.env.QINGCHANG_REAL_AI !== '1' || !fixturePath, '需显式启用并提供真人干声 WAV，以及已就绪的 v2 服务')
  test.setTimeout(360000)
  const fixture = await readFile(fixturePath!)
  await page.goto(process.env.QINGCHANG_REAL_AI_BASE_URL || '/')
  await page.getByRole('button', { name: /偏好设置/ }).click()
  await page.getByRole('button', { name: '保存并检测连接', exact: true }).click()
  await expect(page.getByText('VocalVerse2 MuQ KTV v2 已就绪，可以到「我的作品」开始评估。')).toBeVisible({ timeout: 15000 })
  await page.evaluate(async encoded => {
    const bytes = Uint8Array.from(atob(encoded), character => character.charCodeAt(0))
    const audio = new Blob([bytes], { type: 'audio/wav' })
    const context = new AudioContext()
    const decoded = await context.decodeAudioData(await audio.arrayBuffer())
    await context.close()
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('qingchang-library', 1); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    await new Promise<void>((resolve, reject) => { const tx = db.transaction('recordings', 'readwrite'); tx.objectStore('recordings').put({ id: 'real-vocalverse-human', trackId: 'fixture', trackTitle: '真人清唱', title: '真实模型验收 · 真人清唱', createdAt: Date.now(), duration: decoded.duration, audio, vocalAudio: audio }); tx.oncomplete = () => resolve(); tx.onabort = () => reject(tx.error) }); db.close()
  }, fixture.toString('base64'))
  await page.reload()
  await page.getByRole('button', { name: '我的作品', exact: true }).click()
  const card = page.locator('.recording-card').filter({ hasText: '真实模型验收 · 真人清唱' })
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/v2/score') && response.request().method() === 'POST', { timeout: 300000 })
  await card.getByRole('button', { name: 'VocalVerse 评分', exact: true }).click()
  const response = await responsePromise
  expect(response.status()).toBe(200)
  const report = await response.json()
  expect(report.recordingId).toBe('real-vocalverse-human')
  expect(report.schemaVersion).toBe(2)
  expect(report.analysis.inputKind).toBe('dry-vocal')
  expect(report.analysis.modelCalled).toBe(true)
  expect(report.scorable).toBe(true)
  expect(report.score).toBeGreaterThanOrEqual(0)
  expect(report.score).toBeLessThanOrEqual(100)
  await expect(card.getByText('原生总体参考分 · 干声')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '我的作品', exact: true }).click()
  await expect(card.getByText('原生总体参考分 · 干声')).toBeVisible()
  const persisted = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('qingchang-library', 1); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    return await new Promise<{ aiScore: { id: string } }>((resolve, reject) => { const request = db.transaction('recordings').objectStore('recordings').get('real-vocalverse-human'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
  })
  expect(persisted.aiScore.id).toBe(report.id)
})
